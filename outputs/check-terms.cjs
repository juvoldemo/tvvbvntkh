const { chromium } = require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:430,height:840},deviceScaleFactor:2});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3000/minhhoa2/index.html?embedded=1');
 await page.evaluate(()=>openRiderTerms('R29'));
 const viewer=page.frameLocator('#termsPdfFrame');
 await viewer.locator('canvas').first().waitFor({timeout:30000});
 await page.waitForTimeout(1500);
 const fit=await viewer.locator('canvas').first().evaluate(c=>({width:c.getBoundingClientRect().width,viewport:innerWidth,height:c.height}));
 if(fit.width>fit.viewport||!fit.height)throw Error(JSON.stringify(fit));
 await page.screenshot({path:'outputs/terms-mobile-fixed.png'});
 await viewer.locator('#larger').click();
 await viewer.locator('canvas').first().waitFor();
 await viewer.locator('#fit').click();
 await viewer.locator('canvas').first().waitFor();
 await page.locator('.terms-close').click();
 if(!await page.locator('#riderTermsModal').evaluate(e=>getComputedStyle(e).display==='none'))throw Error('Modal did not close');
 await page.evaluate(()=>openTermsModal({pdfUrl:'Life-Care-2.0_NH02_QTDK.pdf',title:'Life Care'}));
 await viewer.locator('canvas').first().waitFor({timeout:30000});
 await page.setViewportSize({width:375,height:740});
 await page.waitForTimeout(1000);
 const narrow=await viewer.locator('canvas').first().evaluate(c=>({width:c.getBoundingClientRect().width,viewport:innerWidth}));
 if(narrow.width>narrow.viewport)throw Error(JSON.stringify(narrow));
 await page.screenshot({path:'outputs/terms-mobile-375-fixed.png'});
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({rider:fit,main:narrow,errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
