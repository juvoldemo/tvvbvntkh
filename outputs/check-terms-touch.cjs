const {chromium}=require('playwright');
(async()=>{
 const b=await chromium.launch({headless:true});
 const page=await b.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3000/minhhoa2/index.html?embedded=1');
 await page.evaluate(()=>openRiderTerms('R29'));
 const f=page.frameLocator('#termsPdfFrame');
 await f.locator('canvas').first().waitFor({timeout:30000});
 if(await page.locator('.terms-toolbar').isVisible())throw Error('Toolbar visible');
 if(await f.locator('button').count())throw Error('Viewer buttons visible');
 const width=()=>f.locator('.page').first().evaluate(e=>e.getBoundingClientRect().width);
 const initial=await width();
 const cdp=await page.context().newCDPSession(page);
 const send=(type,points)=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints:points.map(([x,y],i)=>({x,y,id:i+1}))});
 await send('touchStart',[[130,300],[250,300]]);
 await send('touchMove',[[80,300],[300,300]]);
 await send('touchEnd',[]);
 await page.waitForTimeout(600);
 const pinched=await width();
 if(pinched<initial*1.5)throw Error('Pinch failed '+pinched);
 await page.touchscreen.tap(160,300);await page.waitForTimeout(90);await page.touchscreen.tap(160,300);
 await page.waitForTimeout(600);
 const reset=await width();
 if(Math.abs(reset-initial)>1)throw Error('Double tap reset failed '+reset);
 await page.touchscreen.tap(160,300);await page.waitForTimeout(90);await page.touchscreen.tap(160,300);
 await page.waitForTimeout(600);
 const doubled=await width();
 if(doubled<initial*1.9)throw Error('Double tap zoom failed');
 await page.touchscreen.tap(160,300);await page.waitForTimeout(90);await page.touchscreen.tap(160,300);
 await page.waitForTimeout(600);
 await page.screenshot({path:'outputs/terms-touch-mobile.png'});
 if(errors.length)throw Error(errors.join('\n'));
 console.log({initial,pinched,reset,doubled,errors});
 await b.close();
})().catch(e=>{console.error(e);process.exit(1)});
