  const table = url.pathname.split("/").pop();
  if (method === "POST") {
    inserted = JSON.parse(String(init?.body));
    return Response.json({ ...inserted, id: table === "forum_comments" ? commentId : id, created_at: "2026-11-23T08:30:00Z" });
  }
  let rows: unknown[] = [];
  if (table === "authorized_users") rows = [account];
  if (table === "forum_topics") rows = [topic];
  if (table === "forum_comments") rows = [];
  const headers = new Headers(init?.headers);
  return Response.json(headers.get("accept")?.includes("vnd.pgrst.object") ? rows[0] || null : rows, { headers: { "Content-Range": `0-${Math.max(0, rows.length - 1)}/${rows.length}` } });
