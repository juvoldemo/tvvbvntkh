function request(path: string, method = "GET", body?: BodyInit, authenticated = true) {
  const headers = new Headers({ Origin: "http://localhost" });
  if (authenticated) headers.set("Cookie", `${USER_COOKIE}=${createUserToken(authorCode)}`);
  if (typeof body === "string") headers.set("Content-Type", "application/json");
  return new NextRequest(`http://localhost${path}`, { method, body, headers });
}
function form(fields: Record<string, string>) {
  const result = new FormData();
  for (const [key, value] of Object.entries(fields)) result.set(key, value);
  return result;
}
